/**
 * Текстовете на един раздел — на трите езика, един до друг.
 *
 * Българският е мярката: от него TypeScript изважда формата, и ако в
 * английския или китайския липсва ред, сборката пада. Така не може да се
 * случи страница, на която половината е преведена, а половината — празна.
 *
 * Текст с число вътре е функция (`(n) => …`), не шаблон с `{n}`: така
 * параметрите се проверяват при сборката, а множественото число се решава
 * на място, както си го иска езикът.
 */

import type { Ezik } from './ezik';

export type Tekstove<T> = Record<Ezik, T>;

export function tekstove<T>(t: { bg: T; en: NoInfer<T>; zh: NoInfer<T> }): Tekstove<T> {
  return t;
}

/** Един ред на трите езика — за списъци с данни, където текстът стои до логиката. */
export type T3 = Record<Ezik, string>;

/** Изброяване на езика: „а, б, в" — на китайски с „、". */
export function izbroi(chasti: string[], ezik: Ezik): string {
  return chasti.join(ezik === 'zh' ? '、' : ', ');
}
