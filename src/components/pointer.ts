/**
 * Хващане на показалеца при влачене.
 *
 * `setPointerCapture` хвърля, ако показалецът с този номер вече не е
 * активен — случва се при синтетични събития и когато пръстът се е
 * вдигнал между събитието и обработката му. Хващането е удобство, не
 * условие: без него влаченето пак работи, стига показалецът да не
 * излезе извън елемента. Затова грешката се поглъща, вместо да събори
 * целия обработчик.
 */
export function capturePointer(element: Element | null | undefined, pointerId: number): void {
  try {
    element?.setPointerCapture(pointerId);
  } catch {
    // няма активен показалец — влаченето продължава без хващане
  }
}
